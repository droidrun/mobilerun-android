"""Generate protocol/.../Constants.kt from conformance/fixtures/constants.json.

Run without arguments from anywhere; CI re-runs it and fails on any diff.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "conformance" / "fixtures" / "constants.json"
TARGET = (
    ROOT / "protocol" / "src" / "commonMain" / "kotlin" / "ai" / "mobilerun" / "stream" / "protocol" / "Constants.kt"
)
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

HEADER = """// Copyright 2026 Mobilerun
// SPDX-License-Identifier: Apache-2.0

// Generated by tool/generate-constants.py from conformance/fixtures/constants.json. Do not edit.

package ai.mobilerun.stream.protocol
"""


def const_object(name, doc, entries):
    for key in entries:
        assert IDENT.match(key), f"not a Kotlin identifier: {key}"
    lines = [f"/** {doc} */", f"public object {name} {{"]
    for key, value in entries.items():
        lines.append(f"    /** `{key}`, wire value {value}. */")
        lines.append(f"    public const val {key}: Int = {value}")
    lines.append("")
    lines.append("    /** Every constant above by name; used to check the table against the shared fixtures. */")
    lines.append("    internal val entries: Map<String, Int> = mapOf(")
    for key in entries:
        lines.append(f'        "{key}" to {key},')
    lines.append("    )")
    lines.append("}")
    return "\n".join(lines)


def main():
    data = json.loads(SOURCE.read_text())
    parts = [
        const_object(
            "ControlMsgType",
            "Message type byte (first byte) of every binary control message.",
            data["control_msg_type"],
        ),
        const_object(
            "AMotionEvent",
            "Motion event actions and mouse button flags used by touch, scroll and hover messages.",
            data["amotion_event"],
        ),
        const_object(
            "AndroidKeys",
            "Key actions, meta state flags and Android key codes used by keycode messages.",
            data["android_keys"],
        ),
    ]
    code_map = data["code_map"]
    rows = "\n".join(f'        "{code}" to {value},' for code, value in code_map.items())
    parts.append(
        "\n".join(
            [
                "/** Browser `KeyboardEvent.code` values mapped to Android key codes. */",
                "public object KeyboardCodes {",
                "    /** Android key code for a `KeyboardEvent.code` string, for example `KeyA` to 29. */",
                "    public val keycodeByCode: Map<String, Int> = mapOf(",
                rows,
                "    )",
                "}",
            ]
        )
    )
    TARGET.write_text(HEADER + "\n" + "\n\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
